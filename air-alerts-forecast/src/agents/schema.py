"""Pydantic schemas for inter-agent communication.

All agents exchange Pydantic objects; hypotheses and decisions are persisted
as JSON artifacts for auditability.
"""
from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field


class AgentRole(str, Enum):
    SPATIAL = "spatial"
    TEMPORAL = "temporal"
    MODELING = "modeling"
    CRITIC = "critic"
    VALIDATION = "validation"
    JUDGE = "judge"


class HypothesisStatus(str, Enum):
    PROPOSED = "proposed"
    CRITIC_PASS = "critic_pass"
    CRITIC_FAIL = "critic_fail"
    VALIDATED = "validated"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


class Hypothesis(BaseModel):
    """A testable research hypothesis generated by a domain agent."""
    id: str
    agent: AgentRole
    title: str
    description: str
    feature_changes: list[str] = Field(
        default_factory=list,
        description="Names of features to add/modify for this hypothesis",
    )
    model_changes: Optional[str] = None
    expected_effect: str
    metric: str = "pr_auc"
    created_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    status: HypothesisStatus = HypothesisStatus.PROPOSED


class CriticVerdict(BaseModel):
    """Critic's review of a hypothesis (no code rewriting)."""
    hypothesis_id: str
    look_ahead_bias: bool = Field(description="True if leakage detected")
    lag_correct: bool
    reproducible: bool
    testable: bool
    comments: list[str] = Field(default_factory=list)
    passed: bool = Field(description="Overall: all checks true")


class ValidationResult(BaseModel):
    """Deterministic validation result for a hypothesis."""
    hypothesis_id: str
    leakage_test_pass: bool
    baseline_pr_auc: float
    hypothesis_pr_auc: float
    pr_auc_delta: float
    rolling_origin_results: list[dict] = Field(default_factory=list)
    folds_improved: int = Field(description="Number of folds where hypothesis beats baseline")
    total_folds: int = 3
    reproducible: bool
    feature_columns: list[str] = Field(default_factory=list)


class JudgeDecision(BaseModel):
    """Final decision: accept only if all criteria hold."""
    hypothesis_id: str
    leakage_pass: bool
    pr_auc_improved: bool
    stable_across_folds: bool
    reproducible: bool
    accepted: bool
    reason: str


class AgentMessage(BaseModel):
    """Envelope for any agent output."""
    sender: AgentRole
    payload: Any
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
